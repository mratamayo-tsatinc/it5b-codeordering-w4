/*
 * Personal Information Display
 * Sample Output:
 * Initial: J
 * Age: 21
 * Status: Active
 * 
 */

public class PersonalInformationDisplay {
    public static void main(String[] args) {
        char initial = 'J';
        int age = 21;

        System.out.println("Initial: " + initial);
        System.out.println("Age: " + age);
        System.out.println("Status: Active");
    }
}
